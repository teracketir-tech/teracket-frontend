import { LINE_CONFIGS, LINE_KINDS } from "../lines/config";
import type { ReportTab } from "../tabs";

/** کلیدِ تبِ مشخصاتِ خودِ فعالیت؛ پنج تبِ دیگر همان `LineKind`ها هستند */
export const ACTIVITY_TAB = "activity";

/**
 * تب‌های دیالوگِ ثبتِ فعالیت — ایشوی ۱۰ و ۴.
 *
 * فرمِ اصلی سه تب دارد (سربرگ / فعالیت‌ها / پیش‌نمایش) و زیرمجموعه‌ها به
 * صورت تبِ داخلِ همین دیالوگ درمی‌آید چون هر ردیف متعلق به همین فعالیت است؛
 * یک ردیف دیگر نه به گزارشِ دیگری می‌رود و نه به فعالیتِ دیگری.
 *
 * تبِ «عوامل انحراف» (ایشوی ۱۲) دیگر نیست: ایشوی ۴ آن را به سلکتِ مالتیِ
 * خودِ «مشخصات فعالیت» برد تا فیلدِ فعالیت و دلایلِ انحرافِ آن یک‌جا دیده
 * شوند و پیمایشِ یک تبِ تقریباً خالی حذف شود.
 *
 * برچسبِ تبِ زیرمجموعه از `entity` همان پیکربندی می‌آید تا دومین فهرستِ نام
 * ساخته نشود (ایشوی ۹ و DRY). تبِ زیرمجموعه تا پیش از ذخیره‌ی فعالیت پیامِ
 * «ابتدا ذخیره کنید» نشان می‌دهد چون مالکِ ردیف هنوز روی سرور نیست.
 */
export const ACTIVITY_TABS: ReportTab[] = [
    { id: ACTIVITY_TAB, title: "مشخصات فعالیت", required: true },
    ...LINE_KINDS.map((kind) => ({ id: kind, title: LINE_CONFIGS[kind].entity, required: false })),
];

/** بعد از ذخیره‌ی «افزودن» سرِ اولین تبِ زیرمجموعه می‌رویم تا ثبت ادامه یابد */
export const FIRST_LINE_TAB = LINE_KINDS[0];
